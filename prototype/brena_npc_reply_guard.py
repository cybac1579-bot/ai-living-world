"""Validate a model's NPC-only reply before any journal write.

No player action or speech is generated by this adapter. This module does not
enable online GPT and intentionally does not persist unverified text.
"""
from __future__ import annotations

from typing import Any


def validate_npc_reply(prepared: dict[str, Any], response: Any, *, current_revision: int) -> dict[str, Any]:
    if type(current_revision) is not int or current_revision != prepared.get("expected_revision"):
        raise ValueError("stale dialogue revision")
    evidence = prepared.get("npc_evidence")
    if not isinstance(evidence, dict) or not isinstance(evidence.get("npc_id"), str):
        raise ValueError("missing authoritative NPC evidence")
    if not isinstance(response, dict) or set(response) != {"npc_id", "speech"}:
        raise ValueError("NPC reply must contain only npc_id and speech")
    if response["npc_id"] != evidence["npc_id"]:
        raise ValueError("speaker does not match observed NPC")
    speech = response["speech"]
    if not isinstance(speech, str) or not speech.strip() or len(speech) > 2000:
        raise ValueError("invalid NPC speech")
    return {"speaker_id": evidence["npc_id"], "text": speech.strip(),
            "source_revision": current_revision}
